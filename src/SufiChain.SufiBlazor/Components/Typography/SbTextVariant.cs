namespace SufiChain.SufiBlazor.Components.Typography;

/// <summary>
/// Typography variants for SbText.
/// </summary>
public enum SbTextVariant
{
    /// <summary>
    /// Body text (default).
    /// </summary>
    Body,

    /// <summary>
    /// Smaller body text.
    /// </summary>
    BodySmall,

    /// <summary>
    /// Lead/introductory text (larger than body).
    /// </summary>
    Lead,

    /// <summary>
    /// Caption text.
    /// </summary>
    Caption,

    /// <summary>
    /// Overline text (uppercase, small).
    /// </summary>
    Overline,

    /// <summary>
    /// Code/monospace text.
    /// </summary>
    Code
}
