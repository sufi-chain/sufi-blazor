/// <summary>
/// Cross-axis alignment options.
/// </summary>
public enum SbAlign
{
    /// <summary>
    /// Align items to the start.
    /// </summary>
    Start,

    /// <summary>
    /// Align items to the center.
    /// </summary>
    Center,

    /// <summary>
    /// Align items to the end.
    /// </summary>
    End,

    /// <summary>
    /// Stretch items to fill the container.
    /// </summary>
    Stretch,

    /// <summary>
    /// Align items to the baseline.
    /// </summary>
    Baseline
}
